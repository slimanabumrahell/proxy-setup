#!/data/data/com.termux/files/usr/bin/bash
# Termux proxy setup.
# - Asks for proxy details (any type: socks5/socks4/http/https, optional user/pass)
# - Stores them locally only (~/.proxy.env, chmod 600)
# - Auto-enables the proxy in every new Termux session
# - Verifies that traffic really goes through the proxy
# This file contains NO sensitive data.

CONF="$HOME/.proxy.env"
TOOLS="$HOME/.proxy-tools.sh"
BLOCK_START="# >>> proxy-setup >>>"
BLOCK_END="# <<< proxy-setup <<<"

GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[1;33m'
NC='\033[0m'

ok()   { echo -e "${GREEN}$*${NC}"; }
warn() { echo -e "${YELLOW}$*${NC}"; }
err()  { echo -e "${RED}$*${NC}"; }

# Percent-encode user/password so special characters (@ : / # etc.) work in the URL
urlencode() {
  local s="$1" out="" c h i
  for (( i=0; i<${#s}; i++ )); do
    c="${s:i:1}"
    case "$c" in
      [a-zA-Z0-9.~_-]) out+="$c" ;;
      *) printf -v h '%%%02X' "'$c"; out+="$h" ;;
    esac
  done
  printf '%s' "$out"
}

# Write the helper file once (quoted heredoc = no expansion now)
write_tools() {
cat > "$TOOLS" <<'EOF'
# Proxy helpers (generated by proxy setup)
[ -f "$HOME/.proxy.env" ] && . "$HOME/.proxy.env"

proxy_on() {
  if [ -z "${PROXY_URL:-}" ]; then
    echo "No proxy configured. Run setup.sh first."
    return 1
  fi
  export ALL_PROXY="$PROXY_URL" all_proxy="$PROXY_URL" \
         HTTP_PROXY="$PROXY_URL" HTTPS_PROXY="$PROXY_URL" \
         http_proxy="$PROXY_URL" https_proxy="$PROXY_URL"
  echo "Proxy ON: ${PROXY_DISPLAY:-configured}"
}

proxy_off() {
  unset ALL_PROXY all_proxy HTTP_PROXY HTTPS_PROXY http_proxy https_proxy
  echo "Proxy OFF"
}

proxy_check() {
  local real proxied
  real=$(curl --noproxy '*' -s --max-time 15 https://api.ipify.org)
  if [ -z "${PROXY_URL:-}" ]; then
    echo "No proxy configured."
    return 1
  fi
  proxied=$(curl -x "$PROXY_URL" -s --max-time 15 https://api.ipify.org)
  echo "Real IP:  ${real:-unknown}"
  echo "Proxy IP: ${proxied:-FAILED}"
  if [ -z "$proxied" ]; then
    echo "Proxy unreachable. Make sure the proxy app is running and you are on the same network."
    return 1
  elif [ "$proxied" = "$real" ]; then
    echo "WARNING: traffic is NOT going through the proxy."
    return 1
  else
    echo "OK: traffic goes through the proxy."
  fi
}

# Auto-enable in every new session
[ -n "${PROXY_URL:-}" ] && proxy_on >/dev/null
EOF
}

# Add a marked block to a shell startup file (replaces old block, no duplicates)
install_hook() {
  local file="$1"
  touch "$file"
  sed -i "/^$BLOCK_START/,/^$BLOCK_END/d" "$file"
  sed -i '/proxy\.env/d' "$file"
  {
    echo "$BLOCK_START"
    echo '[ -f "$HOME/.proxy-tools.sh" ] && . "$HOME/.proxy-tools.sh"'
    echo "$BLOCK_END"
  } >> "$file"
}

echo "=============================="
echo "      Proxy Setup - Termux"
echo "=============================="
echo ""
echo "Proxy types: socks5 | socks4 | http | https"
read -r -p "Proxy type: " PTYPE

case "$PTYPE" in
  socks5) SCHEME="socks5h" ;;
  socks4) SCHEME="socks4a" ;;
  http)   SCHEME="http" ;;
  https)  SCHEME="https" ;;
  *) err "Unsupported proxy type: $PTYPE"; exit 1 ;;
esac

read -r -p "Proxy IP or host: " PHOST
if [ -z "$PHOST" ] || [[ "$PHOST" =~ [[:space:]] ]]; then
  err "Invalid host."; exit 1
fi

read -r -p "Port: " PPORT
if ! [[ "$PPORT" =~ ^[0-9]+$ ]] || [ "$PPORT" -lt 1 ] || [ "$PPORT" -gt 65535 ]; then
  err "Invalid port."; exit 1
fi

read -r -p "Username (leave empty if none): " PUSER
read -r -s -p "Password (leave empty if none): " PPASS
echo ""

if [ -n "$PUSER" ]; then
  AUTH="$(urlencode "$PUSER"):$(urlencode "$PPASS")@"
else
  AUTH=""
fi

DISPLAY_URL="$SCHEME://$PHOST:$PPORT"
PROXY_URL="$SCHEME://$AUTH$PHOST:$PPORT"

# Save config locally with restricted permissions
{
  printf 'PROXY_URL=%q\n' "$PROXY_URL"
  printf 'PROXY_DISPLAY=%q\n' "$DISPLAY_URL"
} > "$CONF"
chmod 600 "$CONF"
ok "Settings saved to $CONF"

# Install helpers and make them load automatically
write_tools
install_hook "$HOME/.bashrc"
install_hook "$HOME/.bash_profile"

# Activate now
. "$TOOLS"
proxy_on

echo ""
ok "Testing connection..."
proxy_check

echo ""
echo "Commands you can use anytime:"
echo "  proxy_on     - enable proxy in this session"
echo "  proxy_off    - disable proxy in this session"
echo "  proxy_check  - verify real IP vs proxy IP"
echo ""
echo "To change the proxy later, run setup.sh again."
echo "Tip: keep the proxy app running in the background and disable battery optimization for it."
